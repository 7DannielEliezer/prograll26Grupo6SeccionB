    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            Postulacion postSel = (Postulacion) cmbPostulacion.getSelectedItem();
            if (postSel == null) {
                JOptionPane.showMessageDialog(this, "Seleccione una postulación.", "Atención", JOptionPane.WARNING_MESSAGE);
                return;
            }

            if (txtSueldoAcordado.getText().trim().isEmpty() || txtCostoServicio.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Ingrese el sueldo acordado y el costo del servicio.", "Atención", JOptionPane.WARNING_MESSAGE);
                return;
            }

            Contratacion c = new Contratacion();
            c.setIdPostulacion(postSel);
            c.setFechaContratacion(new Date());
            c.setSueldoAcordado(new BigDecimal(txtSueldoAcordado.getText().trim()));
            c.setCostoServicio(new BigDecimal(txtCostoServicio.getText().trim()));
            c.setEstado(cmbEstado.getSelectedItem().toString().equalsIgnoreCase("Activo"));
            c.setFacturaList(new ArrayList<>());

            contratacionController.create(c);

            JOptionPane.showMessageDialog(this, "Contratación registrada exitosamente.");
            cargarDatosTabla();
            limpiarFormulario();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese montos numéricos válidos en Sueldo y Costo Servicio.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error al guardar: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void tblContratacionesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblContratacionesMouseClicked
        int fila = tblContrataciones.getSelectedRow();
        if (fila >= 0) {
            idSeleccionado = (Integer) modeloTabla.getValueAt(fila, 0);

            String postTabla = modeloTabla.getValueAt(fila, 1) != null ? modeloTabla.getValueAt(fila, 1).toString() : "";
            for (int i = 0; i < cmbPostulacion.getItemCount(); i++) {
                Postulacion p = (Postulacion) cmbPostulacion.getItemAt(i);
                if (p != null && p.toString().equalsIgnoreCase(postTabla)) {
                    cmbPostulacion.setSelectedIndex(i);
                    break;
                }
            }

            txtSueldoAcordado.setText(modeloTabla.getValueAt(fila, 3) != null ? modeloTabla.getValueAt(fila, 3).toString() : "");
            txtCostoServicio.setText(modeloTabla.getValueAt(fila, 4) != null ? modeloTabla.getValueAt(fila, 4).toString() : "");

            Object estadoVal = modeloTabla.getValueAt(fila, 5);
            cmbEstado.setSelectedItem(estadoVal != null ? estadoVal.toString() : "Activo");
        }
    }//GEN-LAST:event_tblContratacionesMouseClicked

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (idSeleccionado == null) {
            JOptionPane.showMessageDialog(this, "Seleccione un registro de la tabla.");
            return;
        }

        try {
            Contratacion c = contratacionController.findContratacion(idSeleccionado);
            if (c != null) {
                c.setIdPostulacion((Postulacion) cmbPostulacion.getSelectedItem());
                c.setSueldoAcordado(new BigDecimal(txtSueldoAcordado.getText().trim()));
                c.setCostoServicio(new BigDecimal(txtCostoServicio.getText().trim()));
                c.setEstado(cmbEstado.getSelectedItem().toString().equalsIgnoreCase("Activo"));

                if (c.getFacturaList() == null) {
                    c.setFacturaList(new ArrayList<>());
                }

                contratacionController.edit(c);

                JOptionPane.showMessageDialog(this, "Contratación actualizada.");
                cargarDatosTabla();
                limpiarFormulario();
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese montos numéricos válidos.", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error al actualizar: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idSeleccionado == null) {
            JOptionPane.showMessageDialog(this, "Seleccione un registro de la tabla.");
            return;
        }

        int confirmacion = JOptionPane.showConfirmDialog(this, "¿Eliminar contratación seleccionada?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (confirmacion == JOptionPane.YES_OPTION) {
            try {
                contratacionController.destroy(idSeleccionado);

                JOptionPane.showMessageDialog(this, "Contratación eliminada.");
                cargarDatosTabla();
                limpiarFormulario();
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Error al eliminar: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

