    public FrmContratacion(Usuario usuarioLogueado) {
        this();
        this.usuarioLogueado = usuarioLogueado;
        validarPermisos();
    }

    private void validarPermisos() {
        if (usuarioLogueado != null && usuarioLogueado.getIdRol() != null) {
            String nombreRol = usuarioLogueado.getIdRol().getNombreRol().trim();
            if (nombreRol.equalsIgnoreCase("Reclutador Junior") || nombreRol.contains("Junior")) {
                btnGuardar.setEnabled(false);
                btnActualizar.setEnabled(false);
                btnEliminar.setEnabled(false);
            }
        }
    }

    private void configurarTabla() {
        modeloTabla = new DefaultTableModel(
                new Object[]{"ID", "Postulación", "Fecha Contratación", "Sueldo Acordado", "Costo Servicio", "Estado"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblContrataciones.setModel(modeloTabla);
    }

    private void cargarComboPostulaciones() {
        DefaultComboBoxModel<Postulacion> modelCombo = new DefaultComboBoxModel<>();
        List<Postulacion> lista = postulacionController.findPostulacionEntities();
        for (Postulacion p : lista) {
            modelCombo.addElement(p);
        }
        cmbPostulacion.setModel((DefaultComboBoxModel) modelCombo);
    }

    public void cargarDatosTabla() {
        modeloTabla.setRowCount(0);
        List<Contratacion> lista = contratacionController.findContratacionEntities();

        for (Contratacion c : lista) {
            String fechaTexto = c.getFechaContratacion() != null
                    ? formatoFecha.format(c.getFechaContratacion())
                    : "N/A";

            modeloTabla.addRow(new Object[]{
                c.getIdContratacion(),
                c.getIdPostulacion() != null ? c.getIdPostulacion().toString() : "N/A",
                fechaTexto,
                c.getSueldoAcordado(),
                c.getCostoServicio(),
                (c.getEstado() != null && c.getEstado()) ? "Activo" : "Inactivo"
            });
        }
    }

    private void limpiarFormulario() {
        idSeleccionado = null;
        if (cmbPostulacion.getItemCount() > 0) {
            cmbPostulacion.setSelectedIndex(0);
        }
        txtSueldoAcordado.setText("");
        txtCostoServicio.setText("");
        cmbEstado.setSelectedItem("Activo");
        tblContrataciones.clearSelection();
    }

